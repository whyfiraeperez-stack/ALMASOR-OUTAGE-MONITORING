import React, { useState, useEffect, useMemo, useCallback } from 'react';
import { Navbar } from './components/Navbar';
import { KpiMetrics } from './components/KpiMetrics';
import { FilterBar } from './components/FilterBar';
import { NapDownSection } from './components/NapDownSection';
import { StatusCharts } from './components/StatusCharts';
import { ProvinceSection } from './components/ProvinceSection';
import { FormulaLab } from './components/FormulaLab';
import { DataDoctorAgentModal } from './components/DataDoctorAgentModal';
import { OperationsDrawer } from './components/OperationsDrawer';
import { DeployModal } from './components/DeployModal';
import { DatabaseRow, NapDownRow, SnapshotResponse, FilterState, AnomalyReport } from './types/outage';
import { DataDoctorAgent } from './lib/dataDoctor';
import { ShieldAlert, Cpu, Sparkles, HelpCircle, Layers, ExternalLink, GitBranch, RefreshCw, AlertTriangle } from 'lucide-react';

export default function App() {
  const [snapshot, setSnapshot] = useState<SnapshotResponse | null>(null);
  const [isSyncing, setIsSyncing] = useState<boolean>(false);
  const [lastSyncTime, setLastSyncTime] = useState<Date | null>(null);
  const [syncError, setSyncError] = useState<string | null>(null);

  // Auto-refresh timer state
  const [autoRefreshSec, setAutoRefreshSec] = useState<number>(30);
  const [secondsRemaining, setSecondsRemaining] = useState<number>(30);

  // Navigation tab
  const [activeTab, setActiveTab] = useState<string>('overview');

  // Agent self-repair mode toggle
  const [isRepairedMode, setIsRepairedMode] = useState<boolean>(false);

  // Modals and drawers
  const [isDataDoctorOpen, setIsDataDoctorOpen] = useState<boolean>(false);
  const [isDrawerOpen, setIsDrawerOpen] = useState<boolean>(false);
  const [isDeployModalOpen, setIsDeployModalOpen] = useState<boolean>(false);

  // Primary filters
  const [filters, setFilters] = useState<FilterState>({
    month: 'ALL',
    date: 'ALL',
    province: 'ALL',
    status: 'ALL',
    finding: 'ALL',
    rfo: 'ALL',
    concern: 'ALL',
    search: '',
  });

  // Fetch Snapshot from server
  const fetchSnapshot = useCallback(async (force = false) => {
    setIsSyncing(true);
    setSyncError(null);
    try {
      const res = await fetch(`/api/snapshot?refresh=${force ? '1' : '0'}&ts=${Date.now()}`, {
        cache: 'no-store',
      });
      if (!res.ok) {
        throw new Error(`HTTP ${res.status}: Failed to load outage snapshot`);
      }
      const data: SnapshotResponse = await res.json();
      if (data && data.rows) {
        setSnapshot(data);
        setLastSyncTime(new Date());
      }
    } catch (err: any) {
      console.error('Fetch snapshot error:', err);
      setSyncError(err.message || 'Error syncing with Google Sheets');
    } finally {
      setIsSyncing(false);
      setSecondsRemaining(autoRefreshSec > 0 ? autoRefreshSec : 30);
    }
  }, [autoRefreshSec]);

  // Initial fetch
  useEffect(() => {
    fetchSnapshot(false);
  }, []);

  // Countdown timer for auto-refresh
  useEffect(() => {
    if (autoRefreshSec <= 0) return;

    const interval = setInterval(() => {
      setSecondsRemaining((prev) => {
        if (prev <= 1) {
          fetchSnapshot(false);
          return autoRefreshSec;
        }
        return prev - 1;
      });
    }, 1000);

    return () => clearInterval(interval);
  }, [autoRefreshSec, fetchSnapshot]);

  // Handle visibility change (re-sync when user switches back to tab)
  useEffect(() => {
    const onVisibilityChange = () => {
      if (!document.hidden && autoRefreshSec > 0) {
        fetchSnapshot(false);
      }
    };
    document.addEventListener('visibilitychange', onVisibilityChange);
    return () => document.removeEventListener('visibilitychange', onVisibilityChange);
  }, [autoRefreshSec, fetchSnapshot]);

  // Anomaly report generated by the autonomous agent
  const anomalyReport: AnomalyReport = useMemo(() => {
    if (!snapshot) {
      return {
        formulaErrors: [],
        blankFinalStatusRowsCount: 0,
        blankFinalStatusSampleRows: [],
        napDownDiscrepancy: {
          sheetTotal: 0,
          emptyArtifactRows: 0,
          cleanSheetCount: 0,
          pendingFinalStatusCount: 0,
          isIdentical: true,
          explanation: '',
        },
        invertedDatesCount: 0,
        unassignedTechnicianCount: 0,
        cleanRowsCount: 0,
        totalRowsScanned: 0,
        healthScore: 100,
      };
    }
    return DataDoctorAgent.analyze(snapshot.rows, snapshot.napDownRows);
  }, [snapshot]);

  // Self-healed / repaired rows from the agent
  const repairedData = useMemo(() => {
    if (!snapshot) return { repairedRows: [], repairedNapDown: [], repairsMadeCount: 0, log: [] };
    return DataDoctorAgent.repair(snapshot.rows, snapshot.napDownRows);
  }, [snapshot]);

  // Working data (Raw vs Repaired)
  const currentDbRows: DatabaseRow[] = useMemo(() => {
    if (!snapshot) return [];
    return isRepairedMode ? repairedData.repairedRows : snapshot.rows;
  }, [snapshot, isRepairedMode, repairedData]);

  const currentNapDownRows: NapDownRow[] = useMemo(() => {
    if (!snapshot) return [];
    return isRepairedMode ? repairedData.repairedNapDown : snapshot.napDownRows;
  }, [snapshot, isRepairedMode, repairedData]);

  // Distinct months and dates for filter dropdowns
  const { filterMonths, filterDates } = useMemo(() => {
    const monthsSet = new Set<string>();
    const datesSet = new Set<string>();

    currentDbRows.forEach((r) => {
      if (r.dateRestored) {
        const d = r.dateRestored.slice(0, 10);
        datesSet.add(d);
        const m = d.slice(0, 7);
        monthsSet.add(m);
      }
    });

    return {
      filterMonths: Array.from(monthsSet).sort().reverse(),
      filterDates: Array.from(datesSet).sort().reverse(),
    };
  }, [currentDbRows]);

  // Filter application
  const filteredRows = useMemo(() => {
    return currentDbRows.filter((r) => {
      // Month
      if (filters.month !== 'ALL') {
        const d = r.dateRestored ? r.dateRestored.slice(0, 7) : '';
        if (d !== filters.month) return false;
      }
      // Date
      if (filters.date !== 'ALL') {
        const d = r.dateRestored ? r.dateRestored.slice(0, 10) : '';
        if (d !== filters.date) return false;
      }
      // Province
      if (filters.province !== 'ALL' && (r.province || '').toUpperCase() !== filters.province.toUpperCase()) {
        return false;
      }
      // Final Status
      if (filters.status !== 'ALL') {
        const s = (r.finalStatus || 'BLANK').toUpperCase();
        if (s !== filters.status.toUpperCase()) return false;
      }
      // Finding
      if (filters.finding !== 'ALL' && (r.finding || '') !== filters.finding && (r.napStatus || '') !== filters.finding) {
        return false;
      }
      // RFO
      if (filters.rfo !== 'ALL' && (r.rfo || '') !== filters.rfo) {
        return false;
      }
      // Concern
      if (filters.concern !== 'ALL' && (r.concern || '') !== filters.concern) {
        return false;
      }
      // Search text
      if (filters.search.trim()) {
        const q = filters.search.toLowerCase();
        const match =
          (r.municipality || '').toLowerCase().includes(q) ||
          (r.barangay || '').toLowerCase().includes(q) ||
          (r.napStatus || '').toLowerCase().includes(q) ||
          (r.finding || '').toLowerCase().includes(q) ||
          (r.joNumber || '').toLowerCase().includes(q) ||
          (r.ospTeam || '').toLowerCase().includes(q);
        if (!match) return false;
      }
      return true;
    });
  }, [currentDbRows, filters]);

  // Pending rows in filtered scope
  const filteredPendingRows = useMemo(() => {
    return filteredRows.filter((r) => (r.finalStatus || '').toUpperCase() === 'PENDING');
  }, [filteredRows]);

  // Restored rows in filtered scope
  const filteredRestoredRows = useMemo(() => {
    return filteredRows.filter((r) => (r.finalStatus || '').toUpperCase() === 'RESTORED');
  }, [filteredRows]);

  // Pending rate
  const pendingRateFormatted = useMemo(() => {
    if (!filteredRows.length) return '0.0%';
    return `${((filteredPendingRows.length / filteredRows.length) * 100).toFixed(1)}%`;
  }, [filteredPendingRows.length, filteredRows.length]);

  // Province breakdown of pending rows for AI audit
  const pendingByProvince = useMemo(() => {
    const map: Record<string, number> = {};
    filteredPendingRows.forEach((r) => {
      const p = (r.province || '').trim() || 'UNSPECIFIED';
      map[p] = (map[p] || 0) + 1;
    });
    return map;
  }, [filteredPendingRows]);

  // Reset filters handler
  const handleResetFilters = () => {
    setFilters({
      month: 'ALL',
      date: 'ALL',
      province: 'ALL',
      status: 'ALL',
      finding: 'ALL',
      rfo: 'ALL',
      concern: 'ALL',
      search: '',
    });
  };

  return (
    <div className="min-h-screen bg-slate-100 dark:bg-slate-950 text-slate-800 dark:text-slate-100 font-sans selection:bg-teal-500 selection:text-white">
      {/* Top Bar Contract (Strict 3 Zones) */}
      <Navbar
        autoRefreshSec={autoRefreshSec}
        setAutoRefreshSec={setAutoRefreshSec}
        secondsRemaining={secondsRemaining}
        isSyncing={isSyncing}
        onRefreshClick={() => fetchSnapshot(true)}
        isRepairedMode={isRepairedMode}
        setIsRepairedMode={setIsRepairedMode}
        onOpenDataDoctor={() => setIsDataDoctorOpen(true)}
        activeTab={activeTab}
        setActiveTab={setActiveTab}
        pendingCount={filteredPendingRows.length}
      />

      {/* Main Container */}
      <main className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6">
        {/* Agent Health Indicator Strip */}
        <div className="flex flex-wrap items-center justify-between gap-3 p-3 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-lg mb-6 shadow-xs text-xs">
          <div className="flex items-center gap-2.5">
            <span className="w-2.5 h-2.5 rounded-full bg-teal-500"></span>
            <span className="font-bold text-slate-900 dark:text-white tracking-wide uppercase">
              LIVE DATA AGENT
            </span>
            <span aria-hidden="true" className="text-slate-300 dark:text-slate-700">·</span>
            <span className="text-slate-600 dark:text-slate-300">
              Direct Google Sheets Connection Active
            </span>
            <span aria-hidden="true" className="text-slate-300 dark:text-slate-700">·</span>
            <span className="text-slate-500 dark:text-slate-400 font-mono tabular-nums">
              Last synced: {lastSyncTime ? lastSyncTime.toLocaleTimeString() : 'Initializing...'}
            </span>
          </div>

          <div className="flex items-center gap-3">
            {isRepairedMode && (
              <span className="text-[11px] font-semibold text-emerald-600 dark:text-emerald-400 flex items-center gap-1">
                <Sparkles className="w-3.5 h-3.5" />
                <span>Self-Healing Active ({repairedData.repairsMadeCount} cell fixes)</span>
              </span>
            )}
            <button
              onClick={() => setIsDeployModalOpen(true)}
              className="text-xs font-semibold text-slate-700 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white flex items-center gap-1.5 cursor-pointer underline decoration-slate-300 dark:decoration-slate-700"
            >
              <GitBranch className="w-3.5 h-3.5" />
              <span>Deploy to GitHub &amp; Vercel</span>
            </button>
          </div>
        </div>

        {/* Sync Error Banner if any */}
        {syncError && (
          <div className="p-3.5 mb-6 bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-900 rounded-lg text-xs text-rose-800 dark:text-rose-300 flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 text-rose-600 shrink-0" />
            <span>{syncError}. Showing verified fallback snapshot.</span>
          </div>
        )}

        {/* KPI Strip */}
        <KpiMetrics
          totalRecords={filteredRows.length}
          pendingCount={filteredPendingRows.length}
          restoredCount={filteredRestoredRows.length}
          pendingRate={pendingRateFormatted}
          isRepairedMode={isRepairedMode}
          formulaErrorsCount={anomalyReport.formulaErrors.length}
          blankFixedCount={anomalyReport.blankFinalStatusRowsCount}
          onJumpToNapDown={() => setActiveTab('napdown')}
          onOpenDataDoctor={() => setIsDataDoctorOpen(true)}
        />

        {/* Multi-Dimensional Filter Bar */}
        <FilterBar
          filters={filters}
          setFilters={setFilters}
          options={snapshot?.options || {}}
          months={filterMonths}
          dates={filterDates}
          onReset={handleResetFilters}
          isRepairedMode={isRepairedMode}
          setIsRepairedMode={setIsRepairedMode}
          matchCount={filteredRows.length}
          totalCount={currentDbRows.length}
        />

        {/* Dynamic View based on Active Tab or Full View */}
        {activeTab === 'overview' && (
          <>
            {/* NAP Down Section */}
            <NapDownSection
              napDownRows={currentNapDownRows}
              pendingDbCount={filteredPendingRows.length}
            />

            {/* Database Final Status & Comparison Charts */}
            <StatusCharts
              rows={filteredRows}
              totalRows={filteredRows.length}
              pendingCount={filteredPendingRows.length}
              restoredCount={filteredRestoredRows.length}
              selectedDate={filters.date}
            />

            {/* Pending by Province Accordion */}
            <ProvinceSection pendingRows={filteredPendingRows} />

            {/* Formula Laboratory */}
            <FormulaLab />
          </>
        )}

        {activeTab === 'napdown' && (
          <NapDownSection
            napDownRows={currentNapDownRows}
            pendingDbCount={filteredPendingRows.length}
          />
        )}

        {activeTab === 'provinces' && (
          <ProvinceSection pendingRows={filteredPendingRows} />
        )}

        {activeTab === 'formulas' && (
          <FormulaLab />
        )}

        {/* Floating Quick Drawer Trigger Button */}
        <div className="fixed bottom-6 right-6 z-30">
          <button
            onClick={() => setIsDrawerOpen(true)}
            className="px-4 py-2.5 bg-slate-900 text-white hover:bg-slate-800 text-xs font-bold rounded-full shadow-lg border border-slate-700 flex items-center gap-2 cursor-pointer hover:scale-105 active:scale-95 transition-all"
          >
            <Layers className="w-4 h-4 text-teal-400" />
            <span>OPERATIONS DETAILS</span>
          </button>
        </div>
      </main>

      {/* Footer */}
      <footer className="border-t border-slate-200 dark:border-slate-800 py-6 text-xs text-slate-500 dark:text-slate-400">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 flex flex-col sm:flex-row items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <span>Almasor Telecom Operations Center</span>
            <span aria-hidden="true">·</span>
            <span>Google Sheets Synchronizer Active</span>
          </div>
          <div className="flex items-center gap-3">
            <button
              onClick={() => setIsDataDoctorOpen(true)}
              className="text-teal-600 dark:text-teal-400 hover:underline cursor-pointer"
            >
              Data Doctor Agent
            </button>
            <span aria-hidden="true">·</span>
            <button
              onClick={() => setIsDeployModalOpen(true)}
              className="hover:underline cursor-pointer"
            >
              Push to GitHub &amp; Vercel
            </button>
          </div>
        </div>
      </footer>

      {/* Autonomous Data Doctor Modal */}
      <DataDoctorAgentModal
        isOpen={isDataDoctorOpen}
        onClose={() => setIsDataDoctorOpen(false)}
        report={anomalyReport}
        isRepairedMode={isRepairedMode}
        onToggleRepair={() => setIsRepairedMode(!isRepairedMode)}
        repairsLog={repairedData.log}
        pendingCount={filteredPendingRows.length}
        provinceBreakdown={pendingByProvince}
      />

      {/* Operations Drawer */}
      <OperationsDrawer
        isOpen={isDrawerOpen}
        onClose={() => setIsDrawerOpen(false)}
        rows={filteredRows}
        pendingRows={filteredPendingRows}
        restoredRows={filteredRestoredRows}
      />

      {/* GitHub & Vercel Deployment Modal */}
      <DeployModal
        isOpen={isDeployModalOpen}
        onClose={() => setIsDeployModalOpen(false)}
      />
    </div>
  );
}
